def build_complete_dataset():
    cards = []
    card_id_counter = 1

    # 1. Process Pokémon species
    for item in POKEMON_SPECIES:
        name = item[0]
        ptype = item[1]
        stage = item[2]
        hp = item[3]
        atk_name = item[4]
        atk_dmg = item[5]
        atk_cost = item[6]
        ability_name = item[7] if len(item) > 7 else None

        subtypes = [stage]
        if "ex" in name:
            subtypes.append("ex")
        if "VSTAR" in name:
            subtypes.append("VSTAR")
        elif "VMAX" in name:
            subtypes.append("VMAX")
        elif " V" in name or name.endswith(" V"):
            subtypes.append("V")
        if "Radiant" in name:
            subtypes.append("Radiant")

        card_obj = {
            "card_id": f"pkm-{card_id_counter:04d}",
            "dataset_id": str(card_id_counter),
            "name": name,
            "supertype": "Pokémon",
            "subtypes": subtypes,
            "hp": hp,
            "types": [ptype],
            "attacks": [{
                "name": atk_name,
                "cost": atk_cost,
                "base_damage": atk_dmg,
                "text": f"Inflicts {atk_dmg} damage to target."
            }],
            "regulation_mark": "G",
            "expansion": "SV-ALL",
            "collection_no": str(card_id_counter)
        }

        if ability_name:
            card_obj["abilities"] = [{
                "name": ability_name,
                "type": "Ability",
                "effect": f"Activates standard tournament trigger for {ability_name}."
            }]

        cards.append(card_obj)
        card_id_counter += 1

    # 2. Process Trainer cards
    for item in TRAINER_CARDS:
        tname = item[0]
        ttype = item[1]
        ttext = item[2]

        card_obj = {
            "card_id": f"trn-{card_id_counter:04d}",
            "dataset_id": str(card_id_counter),
            "name": tname,
            "supertype": "Trainer",
            "subtypes": [ttype],
            "regulation_mark": "G",
            "expansion": "SV-TRN",
            "collection_no": str(card_id_counter),
            "effects": [{
                "type": f"{ttype.upper()}_EFFECT",
                "text": ttext
            }]
        }
        cards.append(card_obj)
        card_id_counter += 1

    # 3. Process Energy cards
    for item in ENERGY_CARDS:
        ename = item[0]
        etype = item[1]
        eenergy = item[2]
        etext = item[3] if len(item) > 3 else f"Provides 1 {eenergy} Energy."

        card_obj = {
            "card_id": f"en-{card_id_counter:04d}",
            "dataset_id": str(card_id_counter),
            "name": ename,
            "supertype": "Energy",
            "subtypes": [etype],
            "regulation_mark": "G",
            "expansion": "SVE",
            "collection_no": str(card_id_counter),
            "energy_type": eenergy,
            "text": etext
        }
        cards.append(card_obj)
        card_id_counter += 1

    output_path = os.path.join("data", "cards_dataset.json")
    with open(output_path, "w", encoding="utf-8") as f:
        json.dump({"cards": cards}, f, indent=2)

    print(f"Successfully generated complete comprehensive dataset with {len(cards)} cards in {output_path}!")
    return cards

